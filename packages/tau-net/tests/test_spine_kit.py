def test_the_kit_is_complete() -> None:
    kit = load_kit()
    names = {entry.name for entry in kit_root().iterdir()}
    assert KIT_FILES <= names
    assert re.fullmatch(r"\d+\.\d+\.\d+\+[0-9a-f]{12}", kit.version)
    assert kit.worker.startswith(f"// tau spine {kit.version}:".encode())
    assert b"Generated by cloud/spine/scripts/kit.mjs" in kit.worker[:400]
    assert b"sourceMappingURL" not in kit.worker
    assert b"export {" in kit.worker and b"as default" in kit.worker

    config = parse_jsonc(kit.template)
    assert kit.template.startswith(f"// tau spine {kit.version}, local mode")
    assert config["name"] == "tau-spine"
    assert config["main"] == "worker.js"
    assert config["no_bundle"] is True and config["find_additional_modules"] is False
    assert config["vars"]["TAU_MODE"] == "local"
    assert config["vars"]["ADDRESS"] == ""
    assert "routes" not in config and "build" not in config
    assert config["compatibility_date"] and config["triggers"]["crons"]
    assert config["durable_objects"]["bindings"] and config["migrations"]
    for kv in config.get("kv_namespaces", []):
        assert "id" not in kv  # provisioned on the first deploy, never a real id
    for db in config.get("d1_databases", []):
        assert "database_id" not in db and db["migrations_dir"] == "migrations"

    package = json.loads(kit.package)
    assert package["private"] is True
