def test_parse_jsonc() -> None:
    text = '{\n  // a comment\n  "url": "https://x.example/a//b", /* block */ "list": [1, 2,],\n}'
    assert parse_jsonc(text) == {"url": "https://x.example/a//b", "list": [1, 2]}
    assert parse_jsonc('{"a": "quote \\" // not a comment"}') == {"a": 'quote " // not a comment'}
    with pytest.raises(ValueError):
        parse_jsonc("{/* open")


