#!/usr/bin/env bash
# The LiteLLM proxy for tau's model roles: docker compose with the repo's .env.
#
#   ./proxy.sh init     generate the master key, salt key and database password into .env
#   ./proxy.sh up       start (or update) the proxy and its database in the background
#   ./proxy.sh restart  reload config.yaml (it is mounted, so edits need a restart)
#   ./proxy.sh down     stop them; the database volume and every spend record stay
#   ./proxy.sh status   containers, health and the model groups the proxy serves
#   ./proxy.sh logs     follow the proxy log (fallbacks and refused budgets show up here)
#
# Virtual keys and budgets are managed by `uv run tau proxy keys` (see README.md).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
ENV_FILE="${TAU_ENV_FILE:-$ROOT/.env}"

ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
fail() { printf '  \033[31m✗\033[0m %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
die()  { fail "$*"; exit 1; }

compose() {
  docker compose --project-directory "$HERE" -f "$HERE/docker-compose.yml" \
    --env-file "$ENV_FILE" "$@"
}

env_value() {
  # The value of $1 in the .env file (last assignment wins), without quotes.
  [[ -f "$ENV_FILE" ]] || return 0
  sed -n "s/^[[:space:]]*$1=//p" "$ENV_FILE" | tail -n 1 | sed -e 's/^"//' -e 's/"$//' \
    -e "s/^'//" -e "s/'$//"
}

port() {
  local p
  p=$(env_value TAU_PROXY_PORT)
  echo "${p:-4000}"
}

need_docker() {
  command -v docker >/dev/null 2>&1 || die "docker is missing (Docker Desktop on macOS, docker.io on the RPi5)"
  docker info >/dev/null 2>&1 || die "the Docker daemon is not running (start Docker Desktop)"
}

cmd_init() {
  touch "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  local name value added=0
  for name in LITELLM_MASTER_KEY LITELLM_SALT_KEY TAU_PROXY_DB_PASSWORD; do
    if [[ -n "$(env_value "$name")" ]]; then
      ok "$name already set"
      continue
    fi
    case $name in
      TAU_PROXY_DB_PASSWORD) value=$(openssl rand -hex 24) ;;
      *) value="sk-$(openssl rand -hex 24)" ;;
    esac
    [[ -z "$(tail -c 1 "$ENV_FILE")" ]] || printf '\n' >> "$ENV_FILE"
    if (( added == 0 )); then
      printf '\n# --- Models (L2): LiteLLM proxy, generated by infra/litellm/proxy.sh init\n' >> "$ENV_FILE"
    fi
    printf '%s=%s\n' "$name" "$value" >> "$ENV_FILE"
    added=$((added + 1))
    ok "$name generated"
  done
  if [[ -n "$(env_value LITELLM_SALT_KEY)" && $added -eq 0 ]]; then
    info "LITELLM_SALT_KEY never changes once the proxy has run: it encrypts what the database stores."
  fi
  [[ -n "$(env_value ANTHROPIC_API_KEY)" ]] || warn "ANTHROPIC_API_KEY is not set in $ENV_FILE yet"
  info "next: ./proxy.sh up, then uv run tau proxy keys"
}

cmd_up() {
  need_docker
  [[ -n "$(env_value LITELLM_MASTER_KEY)" ]] || die "no LITELLM_MASTER_KEY in $ENV_FILE: run ./proxy.sh init"
  compose up -d --wait
  ok "proxy listening on http://127.0.0.1:$(port)"
}

cmd_restart() {
  need_docker
  compose restart litellm
  compose up -d --wait
  ok "proxy restarted with $HERE/config.yaml"
}

cmd_down() {
  need_docker
  compose down
  ok "proxy stopped (the database volume tau-litellm-db is kept)"
}

cmd_status() {
  need_docker
  compose ps
  local url="http://127.0.0.1:$(port)"
  if curl -fsS -m 3 "$url/health/liveliness" >/dev/null 2>&1; then
    ok "proxy alive at $url"
  else
    fail "proxy not answering at $url"
    return 1
  fi
  local key
  key=$(env_value LITELLM_MASTER_KEY)
  if [[ -n "$key" ]]; then
    curl -fsS -m 5 -H "Authorization: Bearer $key" "$url/v1/models" \
      | python3 -c 'import json,sys; print("    model groups: " + ", ".join(m["id"] for m in json.load(sys.stdin)["data"]))' \
      || warn "could not list the model groups"
  fi
}

cmd_logs() {
  need_docker
  compose logs -f --tail 100 litellm
}

case "${1:-}" in
  init) cmd_init ;;
  up) cmd_up ;;
  restart) cmd_restart ;;
  down) cmd_down ;;
  status) cmd_status ;;
  logs) cmd_logs ;;
  *)
    sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
    ;;
esac
