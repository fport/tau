@dataclass
class Call:
    argv: list[str]
    cwd: Path
    stdin: str | None


@dataclass
class FakeRunner:
    """Answers like npm and Wrangler would; ``answers`` maps an argv prefix to a result."""

    answers: dict[str, Completed] = field(default_factory=dict)
    found: tuple[str, ...] = ("npx", "npm")
    calls: list[Call] = field(default_factory=list)
    echo_stdin: bool = False

    def which(self, name: str) -> str | None:
        return f"/usr/local/bin/{name}" if name in self.found else None

    def run(self, argv, *, cwd, stdin=None, echo=None) -> Completed:
        argv = list(argv)
        self.calls.append(Call(argv, cwd, stdin))
        command = " ".join(argv)
        result = Completed(0, "ok\n")
        for prefix, answer in {**DEFAULT_ANSWERS, **self.answers}.items():
            if command.startswith(prefix):
                result = answer
        if self.echo_stdin and stdin:  # a tool that (wrongly) repeats its input
            result = Completed(result.returncode, result.output + f"got {stdin}")
        if echo is not None:
            for line in result.output.splitlines():
                echo(line)
        return result

    @property
    def argvs(self) -> list[list[str]]:
        return [call.argv for call in self.calls]


DEFAULT_ANSWERS = {
    "npx --yes wrangler@": Completed(0, WHOAMI_IN + "\n"),
    "npm install": Completed(0, "added 38 packages in 5s\n"),
    "npx wrangler deploy": Completed(0, DEPLOY_OUTPUT),
    "npx wrangler d1 migrations apply": Completed(0, "Migrations applied\n"),
    "npx wrangler secret put": Completed(0, "Success! Uploaded secret HUB_TOKEN\n"),
}


def _project(tmp_path: Path, cli, *args: str, d1: bool | None = None) -> Path:
    target = tmp_path / "spine"
    result = cli("spine", "init", str(target), *args)
    assert result.exit_code == 0, _text(result)
    if d1 is not None:
        path = target / "wrangler.jsonc"
        config = parse_jsonc(path.read_text(encoding="utf-8"))
        if d1:
            config["d1_databases"] = [
                {"binding": "DB", "database_name": "tau-spine", "migrations_dir": "migrations"}
            ]
        else:
            config.pop("d1_databases", None)
        path.write_text(json.dumps(config, indent=2), encoding="utf-8")
    return target


def _dotenv(tmp_path: Path) -> dict[str, str]:
    return env_with_dotenv(tmp_path / "home", {})


def _expected(pin: str, *, d1: bool) -> list[list[str]]:
    return [
        ["npx", "--yes", f"wrangler@{pin}", "whoami", "--json"],
        ["npm", "install", "--no-audit", "--no-fund"],
        ["npx", "wrangler", "deploy"],
        *([["npx", "wrangler", "d1", "migrations", "apply", "DB", "--remote"]] if d1 else []),
        ["npx", "wrangler", "secret", "put", "HUB_TOKEN"],
    ]


@pytest.mark.parametrize("d1", [True, False])
def test_deploy_runs_the_steps_and_keeps_the_token_off_the_command_line(
    tmp_path: Path, cli, d1: bool
) -> None:
    target = _project(tmp_path, cli, d1=d1)
    runner = FakeRunner()
    result = cli("spine", "deploy", str(target), spine_runner=runner, spine_environ={})
    assert result.exit_code == 0, _text(result)

    pin = json.loads(load_kit().package)["devDependencies"]["wrangler"]
    assert runner.argvs == _expected(pin, d1=d1)
    assert all(call.cwd == target.resolve() for call in runner.calls)

    env = _dotenv(tmp_path)
    token = env["TAU_SPINE_TOKEN"]
    assert len(token) >= 40
    assert env["TAU_SPINE_URL"] == WORKERS_DEV
    assert stat.S_IMODE((tmp_path / "home" / ".env").stat().st_mode) == 0o600
    for call in runner.calls:
        assert all(token not in arg for arg in call.argv)
    stdins = [call.stdin for call in runner.calls if call.stdin is not None]
    assert stdins == [f"{token}\n"]
    assert runner.calls[-1].stdin == f"{token}\n"
    assert token not in _text(result)
    assert "someone@example.com" not in _text(result)  # whoami's output is never shown

    output = result.output
    assert "Generated a new TAU_SPINE_TOKEN" in output
    assert "Set the Worker's HUB_TOKEN secret to TAU_SPINE_TOKEN." in output
    assert f"Wrote TAU_SPINE_URL={WORKERS_DEV}" in output
    assert f"The spine is deployed at {WORKERS_DEV}." in output
    for step in ("tau net init", "tau net publish", "tau net status"):
        assert step in output
    assert "$ npx wrangler deploy" in output and "Uploaded tau-spine" in output


