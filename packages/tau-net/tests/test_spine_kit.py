def test_the_subprocess_runner_feeds_stdin_and_echoes_lines(tmp_path: Path) -> None:
    lines: list[str] = []
    script = "import sys; data = sys.stdin.read(); print(len(data)); print('done')"
    result = SubprocessRunner().run(
        [sys.executable, "-c", script], cwd=tmp_path, stdin="secret\n", echo=lines.append
    )
    assert result.returncode == 0
    assert lines == ["7", "done"]
    assert result.output.splitlines() == ["7", "done"]
    quiet = SubprocessRunner().run([sys.executable, "-c", "import sys; sys.exit(3)"], cwd=tmp_path)
    assert quiet.returncode == 3
    with pytest.raises(SpineKitError, match="cannot run"):
        SubprocessRunner().run(["tau-no-such-program-anywhere"], cwd=tmp_path)
