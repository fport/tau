#!/usr/bin/env node
// node scripts/gallery.mjs [--count N] [--seed PREFIX]
//
// Development only: writes a gallery of characters (cloud/shared/character.ts) to
// .gallery/index.html, with the theme and the web font next to it, so the creatures can be
// looked at and screenshot side by side. Nothing here is built into the site or deployed:
// .gallery/ lies outside public/ and ignores itself (it writes its own `.gitignore`).
//
// Node 24 runs the TypeScript generator directly (type stripping).

import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { character, traits } from "../../shared/character.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, ".gallery");
const fontSource = join(root, "node_modules", "@fontsource-variable", "jost", "files");

const argv = process.argv.slice(2);
const option = (name, fallback) => {
  const index = argv.indexOf(name);
  return index === -1 ? fallback : argv[index + 1];
};
const count = Math.max(1, Math.min(400, Number(option("--count", "40")) || 40));
const prefix = option("--seed", "");

const TAUS = [
  "alice.example.com",
  "bob.example.net",
  "tau.example.com/@carol",
  "dave.example.org",
  "tau.example.com/@erin",
  "frank.example.com",
  "127.0.0.1:8787",
  "tau.example.com/@grace",
];
const SUBS = ["coach", "landing", "arm", "chef", "tutor", "scout", "poet", "critic"];

/** Seeds like the site's: tau addresses, then `<address>/<name>` for sub-taus. */
function seeds() {
  const list = [];
  if (prefix !== "") {
    for (let i = 0; i < count; i++) list.push(`${prefix}${i}`);
    return list;
  }
  for (let i = 0; list.length < count; i++) {
    const tau = TAUS[i % TAUS.length];
    const round = Math.floor(i / TAUS.length);
    list.push(round === 0 ? tau : `${tau}/${SUBS[(i + round) % SUBS.length]}`);
  }
  return list;
}

const escape = (text) =>
  text.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

const cells = seeds()
  .map((seed) => {
    const t = traits(seed);
    const facts = [t.color, t.body, t.eyes, t.mouth, t.accessory, t.mark, t.glow ? "glow" : ""]
      .filter(Boolean)
      .join(" · ");
    return `<figure class="cell">${character(seed, { size: 120 })}<figcaption><code>${escape(seed)}</code><span>${escape(facts)}</span></figcaption></figure>`;
  })
  .join("\n");

const sizes = [20, 28, 40, 64, 96, 160]
  .map((size) => character("alice.example.com/coach", { size, label: `${size} px` }))
  .join("");

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>tau characters</title>
<link rel="stylesheet" href="theme.css">
<link rel="stylesheet" href="gallery.css">
</head>
<body class="grid-bg">
<main>
<p class="kicker kicker-accent">dev only · cloud/shared/character.ts</p>
<h1 class="chrome">tau characters</h1>
<p class="lead">${count} seeds. Each is deterministic: the same seed draws the same creature in the site and in tau-host.</p>
<section class="sizes" aria-label="Sizes">${sizes}</section>
<section class="cells">
${cells}
</section>
</main>
</body>
</html>
`;

const css = `main { max-width: 76rem; margin: 0 auto; padding: 2rem 1rem 4rem; }
h1 { font-size: 3rem; font-weight: 200; margin: .5rem 0; }
.lead { color: var(--muted); margin-bottom: 1.5rem; }
.sizes { display: flex; align-items: flex-end; gap: 1.5rem; padding: 1rem; border: 1px solid var(--line); margin-bottom: 1.5rem; }
.cells { display: grid; grid-template-columns: repeat(auto-fill, minmax(10.5rem, 1fr)); gap: 0.5rem; }
.cell { display: grid; justify-items: center; gap: .4rem; padding: 1rem .5rem .8rem; border: 1px solid var(--line); background: var(--bg); }
.cell figcaption { display: grid; gap: .2rem; text-align: center; font-size: .72rem; color: var(--muted); }
.cell code { white-space: normal; overflow-wrap: anywhere; font-size: .7rem; }
`;

mkdirSync(join(out, "fonts"), { recursive: true });
writeFileSync(join(out, ".gitignore"), "# Generated by scripts/gallery.mjs; never tracked.\n*\n");
copyFileSync(join(root, "..", "shared", "theme.css"), join(out, "theme.css"));
for (const subset of ["latin", "latin-ext"]) {
  const file = `jost-${subset}-wght-normal.woff2`;
  copyFileSync(join(fontSource, file), join(out, "fonts", file));
}
writeFileSync(join(out, "gallery.css"), css);
writeFileSync(join(out, "index.html"), page);
console.log(`Wrote ${join(out, "index.html")} (${count} characters).`);
